#!/usr/bin/env python3
"""Generate k8s/models/<name>/kustomization.yaml from models.yaml (Chapter 08).

Each overlay patches the 02-Kubernetes vLLM Deployment (root-llms/90-serving/vllm,
on the root cluster: kubectl --context spark-root apply -k k8s/models/<name>):
model, served name, engine flags, memory (request = limit). CI runs
`gen_overlays.py --check` so the committed overlays never drift from the catalog.
"""
import pathlib
import sys

import yaml

LAB = pathlib.Path(__file__).resolve().parent.parent


def _str(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|" if "\n" in data else None)


yaml.add_representer(str, _str, Dumper=yaml.SafeDumper)
BASE = "../../../../../02-Kubernetes/lab/manifests/root-llms/90-serving/vllm"
POOL_UTIL = 0.72        # Σ util of models running together (the root's ~90 GiB LLM memory pool)
VISIBLE_GIB = 121.7     # MemTotal of the GB10


def overlay(m):
    args = ["$(MODEL)", "--served-model-name=$(SERVED_NAME)", "--host=0.0.0.0", "--port=8000",
            f"--gpu-memory-utilization={m['util']:.2f}", f"--max-model-len={m['max_len']}",
            "--enable-prefix-caching", "--download-dir=/models/hf", *m["args"]]
    if m.get("revision"):                      # pinned weights (Chapter 15): the same commit for model + tokenizer
        args += [f"--revision={m['revision']}", f"--tokenizer-revision={m['revision']}"]
    patch = [
        {"op": "replace", "path": "/spec/template/spec/containers/0/args", "value": args},
        {"op": "replace", "path": "/spec/template/spec/containers/0/env/0/value", "value": m["hf"]},
        {"op": "replace", "path": "/spec/template/spec/containers/0/env/1/value", "value": m["name"]},
        {"op": "replace", "path": "/spec/template/spec/containers/0/resources/limits/memory", "value": m["mem"]},
        # request = limit: the 02 base sets both (the scheduler guards the root's shared LLM memory pool)
        {"op": "replace", "path": "/spec/template/spec/containers/0/resources/requests/memory", "value": m["mem"]},
        {"op": "replace", "path": "/metadata/labels/model", "value": m["name"]},
        {"op": "replace", "path": "/spec/template/metadata/labels/model", "value": m["name"]},
    ]
    doc = {"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
           "resources": [BASE],
           "patches": [{"target": {"kind": "Deployment", "name": "vllm"},
                        "patch": yaml.safe_dump(patch, sort_keys=False, width=200)}]}
    gib = m["util"] * VISIBLE_GIB
    if m.get("alone"):
        budget = (f"# Runs ALONE: util {m['util']:.2f} ≈ {gib:.0f} GiB is nearly the whole ~90 GiB LLM pool and the pod\n"
                  f"# holds {m['mem']} of serving-budget's 90 Gi. Park everything else first: other model servers,\n"
                  f"# bge-m3, Open WebUI, LiteLLM (scale to 0) and batch (no training running).\n")
    else:
        budget = (f"# Budget: util {m['util']:.2f} ≈ {gib:.0f} GiB of the pool; models running next to it may add\n"
                  f"# ≤ {POOL_UTIL - m['util']:.2f} more (incl. bge-m3 0.06). Pod memory {m['mem']} (request = limit) of serving-budget's 90 Gi.\n")
    head = (f"# GENERATED by scripts/gen_overlays.py from models.yaml — do not edit.\n"
            f"# {m['name']}: {m['hf']}  (~{m['weights']} weights, util {m['util']:.2f})\n# {m['use']}\n" + budget)
    return head + yaml.safe_dump(doc, sort_keys=False, width=200)


def main():
    check = "--check" in sys.argv
    models = yaml.safe_load(open(LAB / "models.yaml"))["models"]
    for m in models:                          # the catalog must respect the pool rule
        if not 0 < m["util"] <= 0.70:
            sys.exit(f"{m['name']}: util {m['util']} outside (0, 0.70] — one model never takes more than 0.70")
        if m["util"] > POOL_UTIL - 0.06 and not m.get("alone"):
            sys.exit(f"{m['name']}: util {m['util']} leaves no room for bge-m3 (0.06) — mark it 'alone: true'")
        if int(m["mem"].removesuffix("Gi")) < m["util"] * VISIBLE_GIB:
            sys.exit(f"{m['name']}: mem {m['mem']} < util × {VISIBLE_GIB} GiB — the engine would not fit its own pod")
        if int(m["mem"].removesuffix("Gi")) > 88:
            sys.exit(f"{m['name']}: mem {m['mem']} does not fit serving-budget (90 Gi) next to Qdrant")
    drift = 0
    for m in models:
        path = LAB / "k8s" / "models" / m["name"] / "kustomization.yaml"
        text = overlay(m)
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"DRIFT {path.relative_to(LAB)}")
                drift += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(f"{len(models)} overlays {'checked' if check else 'written'}, {drift} drifted")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
