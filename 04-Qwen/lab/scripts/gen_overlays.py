#!/usr/bin/env python3
"""Generate k8s/models/<name>/kustomization.yaml from models.yaml (Chapter 06).

Each overlay patches the 02-Kubernetes vLLM Deployment (root-llms/90-serving/vllm):
image (versions.env VLLM_IMAGE), model, served name, engine flags, memory
(request = limit). It also drops the base's placeholder hf-token Secret, so an
apply never overwrites the token synced from Vault, and makes the token optional
(no Qwen model in the catalog is gated). Entries with `sandbox:` also get
k8s/models/<name>/sandbox/ for the dev-llms vCluster.

  python3 scripts/gen_overlays.py           write the overlays
  python3 scripts/gen_overlays.py --check   CI: overlays match the catalog, memory rule, sets fit the budget
"""
import pathlib
import re
import sys

import yaml

LAB = pathlib.Path(__file__).resolve().parent.parent
BASE = "../../../../../02-Kubernetes/lab/manifests/root-llms/90-serving/vllm"
GIB_VISIBLE = 121.7          # MemTotal of dgx-spark-1 in GiB (02-Kubernetes Chapter 14)
OVERHEAD_GIB = 3.5           # Python, CUDA context, tokenizer, compile cache outside util
C = "/spec/template/spec/containers/0"


def _str(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|" if "\n" in data else None)


yaml.add_representer(str, _str, Dumper=yaml.SafeDumper)


def versions():
    env = {}
    for line in (LAB / "versions.env").read_text().splitlines():
        m = re.match(r"^([A-Z_]+)=(.*)$", line.strip())
        if m:
            env[m[1]] = m[2].split("#")[0].strip().strip('"')
    return env


def gib(q):
    m = re.fullmatch(r"(\d+(?:\.\d+)?)(Gi|Mi)", str(q))
    if not m:
        raise ValueError(f"memory must be like 32Gi or 512Mi, got {q!r}")
    return float(m[1]) / (1024 if m[2] == "Mi" else 1)


def engine_args(m, util, max_len, extra=()):
    args = ["$(MODEL)", "--served-model-name=$(SERVED_NAME)", "--host=0.0.0.0", "--port=8000",
            f"--gpu-memory-utilization={util}", f"--max-model-len={max_len}",
            "--enable-prefix-caching", "--download-dir=/models/hf", *m["args"], *extra]
    if m.get("revision"):
        args += [f"--revision={m['revision']}", f"--tokenizer-revision={m['revision']}"]
    return args


def dump(head, doc):
    return head + yaml.safe_dump(doc, sort_keys=False, width=200)


def kustomization(patch, base, extra=None):
    drop_secret = "$patch: delete\napiVersion: v1\nkind: Secret\nmetadata: {name: hf-token, namespace: llm-serving}\n"
    doc = {"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": [base], **(extra or {}),
           "patches": [{"target": {"kind": "Deployment", "name": "vllm"},
                        "patch": yaml.safe_dump(patch, sort_keys=False, width=200)},
                       {"patch": drop_secret}]}
    return doc


def model_patch(m, image, util, mem, args):
    return [
        {"op": "replace", "path": f"{C}/image", "value": m.get("image", image)},
        {"op": "replace", "path": f"{C}/args", "value": args},
        {"op": "replace", "path": f"{C}/env/0/value", "value": m["hf"]},
        {"op": "replace", "path": f"{C}/env/1/value", "value": m["name"]},
        {"op": "add", "path": f"{C}/env/3/valueFrom/secretKeyRef/optional", "value": True},
        # request = limit: the scheduler guards the root's shared LLM memory pool
        {"op": "replace", "path": f"{C}/resources/limits/memory", "value": mem},
        {"op": "replace", "path": f"{C}/resources/requests/memory", "value": mem},
        {"op": "replace", "path": "/metadata/labels/model", "value": m["name"]},
        {"op": "replace", "path": "/spec/template/metadata/labels/model", "value": m["name"]},
    ]


def overlay(m, image):
    patch = model_patch(m, image, m["util"], m["mem"], engine_args(m, m["util"], m["max_len"]))
    head = (f"# GENERATED by scripts/gen_overlays.py from models.yaml — do not edit.\n"
            f"# {m['name']}: {m['hf']}  (~{m['weights']} weights, util {m['util']}, {m['mem']} request = limit)\n"
            f"# {m['use']}\n")
    return dump(head, kustomization(patch, BASE))


def sandbox_overlay(m, image):
    s = m["sandbox"]
    args = engine_args({**m, "args": [a for a in m["args"] if not a.startswith("--max-num-seqs")]},
                       s["util"], s["max_len"], ["--max-num-seqs=4", "--max-num-batched-tokens=2048", "--enforce-eager"])
    patch = model_patch(m, image, s["util"], s["mem"], args) + [
        {"op": "replace", "path": f"{C}/resources/requests/cpu", "value": "1"},
        # no model-cache PVC inside the vCluster: weights are downloaded into an emptyDir
        {"op": "replace", "path": "/spec/template/spec/volumes/0", "value": {"name": "models", "emptyDir": {"sizeLimit": "10Gi"}}},
        {"op": "replace", "path": "/spec/template/spec/volumes/1/emptyDir/sizeLimit", "value": "512Mi"},
    ]
    head = (f"# GENERATED by scripts/gen_overlays.py from models.yaml — do not edit.\n"
            f"# {m['name']} in the dev-llms sandbox (llm-sandbox: 1500m · 3 Gi · 2 slices, 02-Kubernetes Chapter 04):\n"
            f"# util {s['util']}, {s['mem']} request = limit, eager mode, weights in an emptyDir.\n"
            f"#   kubectl --context dev-llms apply -k k8s/models/{m['name']}/sandbox\n")
    return dump(head, kustomization(patch, "../" + BASE, {"namespace": "llm-sandbox"}))


def lint(cat):
    """Catalog rules from 02-Kubernetes Chapter 14 / root-llms quotas. Returns a list of problems."""
    errs, by_name, b = [], {}, cat["budget"]
    for m in cat["models"]:
        if m["name"] in by_name:
            errs.append(f"duplicate model name {m['name']}")
        by_name[m["name"]] = m
        need = m["util"] * GIB_VISIBLE + OVERHEAD_GIB
        if gib(m["mem"]) < need:
            errs.append(f"{m['name']}: mem {m['mem']} < util {m['util']} × {GIB_VISIBLE} GiB + {OVERHEAD_GIB} GiB = {need:.1f} GiB")
        if not re.fullmatch(r"[a-z0-9][a-z0-9.-]*[a-z0-9]", m["name"]) or len(m["name"]) > 40:
            errs.append(f"{m['name']}: name must be a short DNS-style label (it becomes vllm-<name>)")
    for s in cat.get("sets", []):
        util = sum(by_name[n]["util"] for n in s["models"]) + (b["apps"]["util"] if s["apps"] else 0)
        mem = sum(gib(by_name[n]["mem"]) for n in s["models"]) + (b["apps"]["memory_gi"] if s["apps"] else 0)
        if util > b["util"] + 1e-9:
            errs.append(f"set {s['name']}: Σ util {util:.2f} > {b['util']}")
        if mem > b["memory_gi"]:
            errs.append(f"set {s['name']}: Σ memory {mem:.0f} Gi > serving-budget {b['memory_gi']} Gi")
    return errs


def outputs(cat, image):
    for m in cat["models"]:
        d = LAB / "k8s" / "models" / m["name"]
        yield d / "kustomization.yaml", overlay(m, image)
        if m.get("sandbox"):
            yield d / "sandbox" / "kustomization.yaml", sandbox_overlay(m, image)


def main():
    check = "--check" in sys.argv
    cat = yaml.safe_load(open(LAB / "models.yaml"))
    image = versions()["VLLM_IMAGE"]
    errs = lint(cat)
    for e in errs:
        print(f"CATALOG {e}")
    drift = n = 0
    for path, text in outputs(cat, image):
        n += 1
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"DRIFT {path.relative_to(LAB)}")
                drift += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check:   # overlays for models that left the catalog
        known = {m["name"] for m in cat["models"]}
        for d in sorted((LAB / "k8s" / "models").glob("*/")):
            if d.name not in known:
                print(f"DRIFT k8s/models/{d.name} is not in models.yaml (delete it)")
                drift += 1
    print(f"{n} overlays {'checked' if check else 'written'}, {drift} drifted, {len(errs)} catalog problems")
    return 1 if drift or errs else 0


if __name__ == "__main__":
    sys.exit(main())
